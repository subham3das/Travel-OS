export type NotificationCategory =
  | 'Bookings'
  | 'Payments'
  | 'Trips'
  | 'Announcements'
  | 'Traveler'
  | 'Reviews'
  | 'Refunds'
  | 'Admin'
  | 'Team'
  | 'System';

export type NotificationStatus = 'UNREAD' | 'READ' | 'ARCHIVED';

export type NotificationDateGroup = 'Today' | 'Yesterday' | 'This Week' | 'Earlier';

export interface AgencyNotification {
  id: string; // e.g. NOTIF-2024-001
  category: NotificationCategory;
  title: string;
  description: string;
  timestamp: string; // e.g. "2m ago", "15m ago", "1h ago"
  dateGroup: NotificationDateGroup;
  createdAt: string; // ISO string for sorting
  isUnread: boolean;
  status: NotificationStatus;
  relatedEntityType?: 'BOOKING' | 'TRIP' | 'PAYMENT' | 'PACKAGE' | 'REVIEW' | 'ANNOUNCEMENT' | 'DOCUMENT' | 'SYSTEM';
  relatedEntityId?: string; // e.g. "#BK-20391", "#TRIP-0826"
  relatedEntityName?: string;
  triggeredBy?: string; // e.g. "Subham Das", "System", "ApnaTrip Admin"
  ctaText?: string; // e.g. "View Booking", "View Payment", "Open Trip"
  ctaLink?: string; // e.g. "/agency/bookings", "/agency/trips"
}

